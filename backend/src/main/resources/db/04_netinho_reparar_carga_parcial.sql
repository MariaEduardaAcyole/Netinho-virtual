WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

DECLARE
  v_idosos NUMBER;
  v_familiares NUMBER;
  v_voluntarios NUMBER;
  v_guias NUMBER;
  v_passos NUMBER;
  v_rede NUMBER;
  v_tarefas NUMBER;
  v_atendimentos NUMBER;
  v_alertas NUMBER;
  v_consentimentos NUMBER;
  v_lembretes NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_idosos FROM IDOSO;
  SELECT COUNT(*) INTO v_familiares FROM FAMILIAR;
  SELECT COUNT(*) INTO v_voluntarios FROM VOLUNTARIO;
  SELECT COUNT(*) INTO v_guias FROM GUIA;
  SELECT COUNT(*) INTO v_passos FROM PASSO;
  SELECT COUNT(*) INTO v_rede FROM REDE_APOIO;
  SELECT COUNT(*) INTO v_tarefas FROM TAREFA;
  SELECT COUNT(*) INTO v_atendimentos FROM ATENDIMENTO;
  SELECT COUNT(*) INTO v_alertas FROM ALERTA_GOLPE;
  SELECT COUNT(*) INTO v_consentimentos FROM CONSENTIMENTO;
  SELECT COUNT(*) INTO v_lembretes FROM LEMBRETE;

  IF v_idosos <> 0 OR v_familiares <> 6 OR v_voluntarios <> 5
     OR v_guias <> 6 OR v_passos <> 19 OR v_rede <> 0
     OR v_tarefas <> 0 OR v_atendimentos <> 0 OR v_alertas <> 0
     OR v_consentimentos <> 0 OR v_lembretes <> 0 THEN
    RAISE_APPLICATION_ERROR(-20001,
      'Carga diferente da parcial esperada. Nenhum dado foi alterado.');
  END IF;

  EXECUTE IMMEDIATE 'ALTER TABLE IDOSO MODIFY (tp_ido_voz VARCHAR2(9))';
  EXECUTE IMMEDIATE 'ALTER TABLE ATENDIMENTO DROP CONSTRAINT ck_ate_atendente';
  EXECUTE IMMEDIATE q'[
    ALTER TABLE ATENDIMENTO ADD CONSTRAINT ck_ate_atendente CHECK (
      (id_fam IS NULL AND id_vol IS NULL AND st_ate IN ('SOLICITADO','CANCELADO'))
      OR (id_fam IS NOT NULL AND id_vol IS NULL AND st_ate <> 'SOLICITADO')
      OR (id_fam IS NULL AND id_vol IS NOT NULL AND st_ate <> 'SOLICITADO')
    )
  ]';
END;
